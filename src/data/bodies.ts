  bandFreq: number;
  bandTurb: number;
  bandAmp: number;
  noiseScale: number;
  noiseAmp: number;
  ridgeScale: number;
  ridgeAmp: number;
  craterScale: number;
  craterAmp: number;
  /** 0 = desligado; >0 = latitude (0..1) onde calotas começam */
