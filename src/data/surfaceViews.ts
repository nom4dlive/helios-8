export interface SkyBodyDef {
  id: string;
  name: string;
  /** diâmetro angular aparente em graus */
  angularDeg: number;
  color: string;
  /** 0 = baixo; 1 = visível mas sem destaque; 2 = dominante */
  glow: number;
  elevationDeg: number;
  azimuthDeg: number;
}

export interface SurfaceViewDef {
  bodyId: string;
  viewLabel: string;
  skyTop: string;
  skyHorizon: string;
  sunAngularDeg: number;
  sunElevationDeg: number;
  sunAzimuthDeg: number;
  sunVisible: boolean;
  sunColor: string;
  starsVisible: boolean;
  starDensity: number;
  terrainBase: string;
  terrainMid: string;
  terrainDark: string;
  terrainScale: number;
  terrainAmp: number;
  gravityMs2: number;
  temperature: string;
  pressure: string;
  dayLength: string;
  skyBodies: SkyBodyDef[];
  effects: "none" | "dust" | "haze" | "clouds";
  fogColor: string;
  fogDensity: number;
  cloudSea?: boolean;
  notes: string[];
  realism?: {
    /** 0 = disco solar nítido · 1 = brilho difuso filtrado por nuvens (Vênus/Titã) */
    sunDiffuse?: number;
    sunStrength?: number;
    sunTint?: string;
    ambient?: number;
    sparkle?: number;
    milkyWay?: number;
    skyBands?: { amp: number; scale: number; drift: number; colorA: string; colorB: string };
    dunes?: number;
    rockField?: { count: number; maxScale: number; colorA: string; colorB: string };
    plume?: {
      colorA: string;
      colorB: string;
      x: number;
      z: number;
      count: number;
      speed: number;
      gravity: number;
      spread: number;
      wind: number;
    };
  };
}

